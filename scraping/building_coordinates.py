"""Look up map coordinates (and street addresses) for the buildings in nusublet_buildings.json.

Writes output/coordinates/building_coordinates.sql, which fills public.buildings.latitude,
longitude and address where they are still empty, matched on buildings.slug. Like the rest of
scraping/, it never connects to Supabase: review the output, then load the SQL yourself.

Where a point comes from, most trusted first:
  sam_address      Boston's official address list (SAM) for the building's street address.
                   Also fills buildings.address when it's empty.
  street_midpoint  "street" pages (e.g. Mission Hill streets): middle of the street's
                   address points, the same point building_specs.py uses for walk times.
  osm_name         Last resort for buildings with no address (halls, complexes): an
                   OpenStreetMap search by name near campus. Check these in the review file.

    python3 building_coordinates.py                       # first run a few minutes, cached after
    python3 building_coordinates.py --only van-ness,lightview
    python3 building_coordinates.py --no-osm              # official city data only

A wrong or missing point: fix street_address (or aliases) in nusublet_buildings.json and rerun.
Already loaded a wrong point: clear latitude/longitude in the dashboard, then load again.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
import urllib.parse
from pathlib import Path

import boston_open_data as city
import building_specs as specs

OUT = specs.HERE / "output" / "coordinates"
NOMINATIM = "https://nominatim.openstreetmap.org/search"
# Box around campus (lon/lat) that OpenStreetMap matches must fall inside: Back Bay to
# Jamaica Plain, Brookline line to the South End. Keeps a common name from matching elsewhere.
VIEWBOX = (-71.125, 42.360, -71.055, 42.315)
# Nominatim's usage policy allows at most one request per second.
NOMINATIM_GAP_S = 1.1
MIN_GAP_DEFAULT = city.MIN_GAP_S


def sam_point(b: specs.Row) -> specs.Row | None:
    for candidate in specs.address_candidates(b, []):
        row = city.lookup_address(candidate)
        if row and row["POINT_X"] and row["POINT_Y"]:
            return {"method": "sam_address", "matched": row["FULL_ADDRESS"],
                    "address": f"{row['FULL_ADDRESS']}, Boston, MA",
                    "lon": float(row["POINT_X"]), "lat": float(row["POINT_Y"])}
    return None


def street_point(b: specs.Row) -> specs.Row | None:
    found = specs.street_point(b)
    if not found:
        return None
    street, (lon, lat) = found
    return {"method": "street_midpoint", "matched": street, "address": None,
            "lon": lon, "lat": lat}


def phrase(text: str) -> str:
    return " " + " ".join(re.findall(r"[a-z0-9]+", text.lower())) + " "


def same_name(searched: str, found: str) -> bool:
    """'West Village A' ~ 'West Village A South', but not 'Church Park' ~ 'Park Street Church'."""
    a, b = phrase(searched), phrase(found)
    return len(a.strip()) > 0 and len(b.strip()) > 0 and (a in b or b in a)


def osm_point(b: specs.Row) -> specs.Row | None:
    west, north, east, south = VIEWBOX
    for name in [b["name"], *b.get("aliases", [])]:
        query = urllib.parse.urlencode({
            "q": f"{name}, Boston, MA", "format": "jsonv2", "limit": 3, "countrycodes": "us",
            "viewbox": f"{west},{north},{east},{south}", "bounded": 1})
        city.MIN_GAP_S = NOMINATIM_GAP_S
        try:
            results = city.fetch_json(f"{NOMINATIM}?{query}")
        finally:
            city.MIN_GAP_S = MIN_GAP_DEFAULT
        # Nominatim also matches words in any order, so check the result's own name.
        r = next((r for r in results if same_name(name, r.get("name") or "")), None)
        if r:
            return {"method": "osm_name", "matched": r.get("display_name", name), "address": None,
                    "lon": float(r["lon"]), "lat": float(r["lat"])}
    return None


def locate(b: specs.Row, use_osm: bool) -> specs.Row | None:
    if b["type"] == "planned":
        return None
    if b["type"] == "street":
        return street_point(b)
    return sam_point(b) or (osm_point(b) if use_osm else None)


def write_sql(found: list[tuple[specs.Row, specs.Row]]) -> Path:
    rows = [f"  ({city.q(b['id'])}, {city.sql_literal(p['address'])}, "
            f"{p['lat']:.6f}, {p['lon']:.6f})" for b, p in found]
    lines = [
        "-- Generated by scraping/building_coordinates.py.",
        "-- Fills public.buildings latitude/longitude and address where they are still empty,",
        "-- matched on slug. Never overwrites a value already there; to replace one, clear it in",
        "-- the dashboard and rerun. Safe to rerun. The last query lists slugs that didn't match.",
        "begin;",
        "",
        "create temp table geo (slug text primary key, address text, "
        "latitude double precision, longitude double precision) on commit drop;",
        "insert into geo (slug, address, latitude, longitude) values",
        ",\n".join(rows) + ";",
        "",
        "update public.buildings b set latitude = g.latitude, longitude = g.longitude",
        "from geo g where b.slug = g.slug and b.latitude is null and b.longitude is null;",
        "",
        "update public.buildings b set address = g.address",
        "from geo g where b.slug = g.slug and b.address is null and g.address is not null;",
        "",
        "select g.slug as not_loaded from geo g",
        "where not exists (select 1 from public.buildings b where b.slug = g.slug)",
        "order by g.slug;",
        "",
        "commit;",
    ]
    path = OUT / "building_coordinates.sql"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_review(results: list[tuple[specs.Row, specs.Row | None]]) -> Path:
    path = OUT / "coordinates_review.csv"
    order = {"osm_name": 0, None: 1, "street_midpoint": 2, "sam_address": 3}
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["slug", "name", "type", "method", "matched", "address", "latitude",
                    "longitude", "distance_to_campus_m", "maps_link"])
        for b, p in sorted(results, key=lambda r: (order[r[1] and r[1]["method"]], r[0]["id"])):
            if not p:
                w.writerow([b["id"], b["name"], b["type"], "", "", "", "", "", "", ""])
                continue
            w.writerow([b["id"], b["name"], b["type"], p["method"], p["matched"],
                        p["address"] or "", f"{p['lat']:.6f}", f"{p['lon']:.6f}",
                        city.distance_m(p["lon"], p["lat"], *city.CAMPUS),
                        f"https://www.openstreetmap.org/?mlat={p['lat']:.6f}"
                        f"&mlon={p['lon']:.6f}#map=18/{p['lat']:.6f}/{p['lon']:.6f}"])
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n", maxsplit=1)[0])
    parser.add_argument("--input", default=specs.DEFAULT_INPUT, type=Path,
                        help="building list (default: oasis-fall-26/nusublet_buildings.json)")
    parser.add_argument("--only", help="comma-separated building ids")
    parser.add_argument("--no-osm", action="store_true",
                        help="don't fall back to OpenStreetMap name search")
    args = parser.parse_args()
    city.load_env(specs.HERE / ".env")

    only = {s.strip() for s in args.only.split(",")} if args.only else None
    buildings = specs.load_buildings(args.input, only)
    OUT.mkdir(parents=True, exist_ok=True)

    results: list[tuple[specs.Row, specs.Row | None]] = []
    for i, b in enumerate(buildings, 1):
        print(f"[{i}/{len(buildings)}] {b['id']}", file=sys.stderr)
        p = locate(b, use_osm=not args.no_osm)
        if not p and b["type"] != "planned":
            print(f"    ! no location found for {b['id']}", file=sys.stderr)
        results.append((b, p))

    found = [(b, p) for b, p in results if p]
    sql_path = write_sql(found) if found else None
    review_path = write_review(results)

    counts = {m: sum(1 for _, p in found if p["method"] == m)
              for m in ("sam_address", "street_midpoint", "osm_name")}
    missing = [b["id"] for b, p in results if not p]
    print("\n" + "=" * 70)
    print(f"Located {len(found)} of {len(buildings)} buildings")
    print(f"  {counts['sam_address']:4d}  city address list (also fills address)")
    print(f"  {counts['street_midpoint']:4d}  middle of the street")
    print(f"  {counts['osm_name']:4d}  OpenStreetMap name search (check these first)")
    print(f"  {len(missing):4d}  not found (planned buildings are skipped)")
    print(f"\nReview: {review_path.relative_to(specs.HERE)}")
    print("  osm_name rows come first; open maps_link to check the pin is on the building.")
    print("  Fix wrong ones by adding street_address in nusublet_buildings.json, then rerun.")
    if sql_path:
        print(f"\nTo load ({sql_path.relative_to(specs.HERE)}):")
        print("  local:       psql postgresql://postgres:postgres@127.0.0.1:54322/postgres "
              f"-f {sql_path.relative_to(specs.HERE)}")
        print("  production:  paste it into the Supabase dashboard's SQL editor")
        print("Only empty latitude/longitude/address values are filled.")


if __name__ == "__main__":
    main()
